import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { it } from 'vitest';
import { DEFAULT_SCOPE, type ConversationScope } from '@/domain/agent/scope';
import { DEMO_AS_OF } from '@/domain/demo-window';
import { buildDemoSeedState } from '@/fixtures/demo-seed';
import { createFixtureTrafficRepository } from '@/repositories/traffic-repository';
import { resolveLiveModel } from '@/services/agent/live-config';
import { runAgentTurn, type PriorTurn } from '@/services/agent/orchestrator';
import { parseReplay, type Replay, type ReplayTurn } from '@/services/agent/replays';

/**
 * Records one conversation per scenario and writes it to
 * src/fixtures/agent-replays/<id>.json, then regenerates the index.
 *
 *   AGENT_LIVE_ENABLED=true AGENT_MODEL_PROVIDER=openai npm run agent:record
 *   REPLAY_SCENARIOS=lookup npm run agent:record        # one scenario
 *   REPLAY_ID_PREFIX=scripted npm run agent:record      # id prefix
 *
 * Each conversation starts from the default scope on the seed catalogue;
 * follow-ups carry the history and the scope, exactly as the page does.
 */

const SCENARIOS: Record<string, { title: string; questions: string[] }> = {
  review: {
    title: '30-day storefront review, then "only organic search?"',
    questions: ['过去 30 天，独立站最该优先排查什么？', '只看自然搜索呢？'],
  },
  lookup: {
    title: 'Lookup with no alert: Ridgeline purchasing sessions from organic search',
    questions: ['过去 30 天 Ridgeline 从自然搜索获得多少购买会话？'],
  },
  'write-request': {
    title: 'A request to change something the agent cannot change',
    questions: ['把第一条建议标记为完成'],
  },
};

const DIR = path.join(process.cwd(), 'src/fixtures/agent-replays');

function writeIndex(): void {
  const files = readdirSync(DIR).filter((name) => name.endsWith('.json')).sort();
  const imports = files.map((file, index) => `import replay${index} from './${file}';`).join('\n');
  const list = files.map((_, index) => `replay${index}`).join(', ');
  writeFileSync(
    path.join(DIR, 'index.ts'),
    `/**\n * Bundled agent replays. Regenerated by \`npm run agent:record\`; do not edit by hand.\n */\n${imports}${imports === '' ? '' : '\n\n'}export const REPLAY_FILES: readonly unknown[] = [${list}];\n`,
  );
}

it('records agent replays', async () => {
  const live = resolveLiveModel(process.env);
  if (!live.ok) throw new Error(`${live.error}: ${live.message}`);
  const model = live.model;
  const source = model.id.startsWith('scripted:') ? 'scripted' : 'live-model';
  const prefix = process.env['REPLAY_ID_PREFIX'] ?? (source === 'scripted' ? 'scripted' : 'live');
  const wanted = (process.env['REPLAY_SCENARIOS'] ?? Object.keys(SCENARIOS).join(',')).split(',').map((name) => name.trim());

  for (const name of wanted) {
    const scenario = SCENARIOS[name];
    if (scenario === undefined) throw new Error(`Unknown scenario "${name}". Known: ${Object.keys(SCENARIOS).join(', ')}`);

    let scope: ConversationScope = DEFAULT_SCOPE;
    const history: PriorTurn[] = [];
    const turns: ReplayTurn[] = [];
    for (const question of scenario.questions) {
      const result = await runAgentTurn(
        { question, history, scope },
        { model, traffic: createFixtureTrafficRepository(), state: { source: 'seed', value: buildDemoSeedState() }, now: () => new Date().toISOString() },
      );
      turns.push({ question, scopeBefore: scope, result });
      history.push({ question, answerSummary: result.answer === null ? (result.message ?? '') : result.answer.summary.map((segment) => segment.text).join('') });
      scope = result.scope;
      // A short, key-free trace for the operator running the recording.
      process.stdout.write(
        `[${name}] ${question}\n  status=${result.status} calls=${result.toolCalls.map((call) => `${call.name}:${call.status}`).join(', ')}\n  issues=${result.issues.map((issue) => issue.code).join(', ') || 'none'} findings=${result.answer?.findings.length ?? 0} facts=${result.answer?.facts.length ?? 0} usage=${JSON.stringify(result.usage)}\n`,
      );
    }

    const replay: Replay = {
      version: 1,
      id: `${prefix}-${name}`,
      title: scenario.title,
      source,
      model: model.id,
      recordedAt: new Date().toISOString(),
      demoAsOf: DEMO_AS_OF,
      stateSource: 'seed',
      turns,
    };
    const checked = parseReplay(JSON.parse(JSON.stringify(replay)));
    if (!checked.ok) throw new Error(checked.error);
    writeFileSync(path.join(DIR, `${replay.id}.json`), `${JSON.stringify(replay, null, 2)}\n`);
  }
  writeIndex();
});
